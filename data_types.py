# Learning some basic data types in Python

name = "Vartika"       # String
age = 20               # Integer
height = 5.2           # Float
is_student = True      # Boolean

# Printing the values
print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Student:", is_student)

# Checking the type of each value
print(type(name))
print(type(age))
print(type(height))
print(type(is_student))